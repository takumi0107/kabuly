// GetAllStocks returns all stocks ordered by category then ticker.
func GetAllStocks(db *sql.DB) ([]Stock, error) {
	rows, err := db.Query(
		"SELECT id, ticker, name, market, category, COALESCE(purchase_price,0), COALESCE(purchase_date,''), created_at FROM stocks ORDER BY category, market, ticker",
	)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	var stocks []Stock
	for rows.Next() {
		var s Stock
		if err := rows.Scan(&s.ID, &s.Ticker, &s.Name, &s.Market, &s.Category,
			&s.PurchasePrice, &s.PurchaseDate, &s.CreatedAt); err != nil {
			return nil, err
		}
		stocks = append(stocks, s)
	}
	return stocks, rows.Err()
}

// GetStock returns a single stock by ticker, or nil if not found.
func GetStock(db *sql.DB, ticker string) (*Stock, error) {
	row := db.QueryRow(
		"SELECT id, ticker, name, market, category, COALESCE(purchase_price,0), COALESCE(purchase_date,''), created_at FROM stocks WHERE ticker = ?",
		ticker,
	)
	var s Stock
	err := row.Scan(&s.ID, &s.Ticker, &s.Name, &s.Market, &s.Category,
		&s.PurchasePrice, &s.PurchaseDate, &s.CreatedAt)
	if err == sql.ErrNoRows {
		return nil, nil
	}
	return &s, err
}

// AddStock inserts or replaces a stock record.
func AddStock(db *sql.DB, s Stock) error {
	_, err := db.Exec(
		`INSERT OR REPLACE INTO stocks (ticker, name, market, category, purchase_price, purchase_date)
		 VALUES (?, ?, ?, ?, ?, ?)`,
		s.Ticker, s.Name, s.Market, s.Category,
		nullFloat(s.PurchasePrice), nullString(s.PurchaseDate),
	)
	return err
}

// DeleteStock removes a stock and its chat history.
func DeleteStock(db *sql.DB, ticker string) error {
	tx, err := db.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err := tx.Exec("DELETE FROM stocks WHERE ticker = ?", ticker); err != nil {
		return err
	}
	if _, err := tx.Exec("DELETE FROM chat_history WHERE ticker = ?", ticker); err != nil {
		return err
	}
	return tx.Commit()
}

