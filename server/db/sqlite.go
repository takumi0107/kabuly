// Package db provides read-only access to the shared SQLite database produced
// by the Python analysis pipeline. The Go server only reads data; all writes
// are done by the Python side except for chat history and profile updates.
package db

import (
	"database/sql"
	"log"
	"os"
	"path/filepath"
	"time"

	_ "github.com/mattn/go-sqlite3"
)

// ─────────────────────────────────────────────────────────
// Domain types
// ─────────────────────────────────────────────────────────

// Stock represents a registered stock (holding or watchlist).
type Stock struct {
	ID            int64
	Ticker        string
	Name          string
	Market        string
	Category      string
	PurchasePrice float64
	PurchaseDate  string
	CreatedAt     string
}

// DailyReport holds the Claude-generated analysis for one stock on one day.
type DailyReport struct {
	ID                 int64
	Ticker             string
	ReportDate         string
	Price              float64
	PriceChangePct     float64
	Signal             string
	Confidence         int
	Reason             string
	TargetPrice        float64
	StopLoss           float64
	RecommendedAmount  float64
	RecommendedShares  int
	RSI                float64
	MA20               float64
	MA50               float64
	MA200              float64
	MACD               float64
	BusinessSummaryJa  string
	RawAnalysis        string
	CreatedAt          string
}

// NewsItem stores a single news article linked to a stock (or macro).
type NewsItem struct {
	ID          int64
	Ticker      string
	Title       string
	Summary     string
	Sentiment   string
	Source      string
	URL         string
	PublishedAt string
	ReportDate  string
}

// DailyInsight is the educational "insight corner" generated by Claude.
type DailyInsight struct {
	ID                int64
	ReportDate        string
	Headline          string
	Explanation       string
	ImpactOnHoldings  string
	Keyword           string
	KeywordExplanation string
	RelatedTickers    string
}

// ChatMessage is one turn in the per-ticker chat history.
type ChatMessage struct {
	Role      string
	Content   string
	CreatedAt string
}

// UserProfile holds the user's investment settings.
type UserProfile struct {
	ID         int64
	Style      string
	LineUserID string
	UpdatedAt  string
}

