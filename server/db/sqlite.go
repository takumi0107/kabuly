// GetChatHistory returns up to limit messages for a ticker in chronological order.
func GetChatHistory(db *sql.DB, ticker string, limit int) ([]ChatMessage, error) {
	rows, err := db.Query(
		`SELECT role, content, created_at FROM chat_history
		 WHERE ticker = ? ORDER BY id DESC LIMIT ?`,
		ticker, limit,
	)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	var msgs []ChatMessage
	for rows.Next() {
		var m ChatMessage
		if err := rows.Scan(&m.Role, &m.Content, &m.CreatedAt); err != nil {
			return nil, err
		}
		msgs = append(msgs, m)
	}
	if rows.Err() != nil {
		return nil, rows.Err()
	}
	// Reverse to chronological order
	for i, j := 0, len(msgs)-1; i < j; i, j = i+1, j-1 {
		msgs[i], msgs[j] = msgs[j], msgs[i]
	}
	return msgs, nil
}

// AppendChat saves one chat message to the database.
func AppendChat(db *sql.DB, ticker, role, content string) error {
	_, err := db.Exec(
		"INSERT INTO chat_history (ticker, role, content) VALUES (?, ?, ?)",
		ticker, role, content,
	)
	return err
}

// ClearChatHistory deletes all messages for a ticker.
func ClearChatHistory(db *sql.DB, ticker string) error {
	_, err := db.Exec("DELETE FROM chat_history WHERE ticker = ?", ticker)
	return err
}

