// Open opens (or creates) the SQLite database at the given path.
// Caller is responsible for calling Close().
func Open(dbPath string) *sql.DB {
	if err := os.MkdirAll(filepath.Dir(dbPath), 0o755); err != nil {
		log.Fatalf("db: cannot create data dir: %v", err)
	}
	conn, err := sql.Open("sqlite3", dbPath+"?_journal_mode=WAL&_foreign_keys=on")
	if err != nil {
		log.Fatalf("db: open error: %v", err)
	}
	conn.SetMaxOpenConns(1) // SQLite supports only one writer at a time
	return conn
}

